export function generateJsonLdSchemas(pageData: PageSeoData) {
  const webAppSchema = {
    '@context': 'https://schema.org',
    '@type': ['WebApplication', 'SoftwareApplication'],
    name: `${SITE_NAME} — ${pageData.h1}`,
    url: pageData.canonicalUrl,
    description: pageData.metaDescription,
    applicationCategory: 'UtilityApplication',
    operatingSystem: 'All',
    browserRequirements: 'Requires JavaScript and HTML5 Canvas support',
    inLanguage: 'bg-BG',
    isAccessibleForFree: true,
    offers: {
      '@type': 'Offer',
      price: '0',
      priceCurrency: 'USD',
    },
    featureList: [
      '100% Client-Side RAM PDF Processing',
      'PDF to High-Resolution JPG & ZIP Archive',
      'PDF to Editable Word (.doc) Export',
      'PDF to Plain Text (.txt) Extraction',
      'Zero Server Uploads — Complete GDPR Privacy',
    ],
    publisher: {
      '@type': 'Organization',
      name: SITE_NAME,
      url: SITE_URL,
    },
  };

  const howToSchema = {
    '@context': 'https://schema.org',
    '@type': 'HowTo',
    name: pageData.howToTitle,
    description: pageData.metaDescription,
    totalTime: 'PT15S',
    tool: [
      {
        '@type': 'HowToTool',
        name: 'Уеб браузър (Chrome, Firefox, Edge, Safari)',
      },
    ],
    step: pageData.howToSteps.map((step, index) => ({
      '@type': 'HowToStep',
      position: index + 1,
      name: step.name,
      text: step.text,
      url: `${pageData.canonicalUrl}#step-${index + 1}`,
    })),
  };

  const faqSchema = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: pageData.faqs.map((faq) => ({
      '@type': 'Question',
      name: faq.question,
      acceptedAnswer: {
        '@type': 'Answer',
        text: faq.answer,
      },
    })),
  };

  return [webAppSchema, howToSchema, faqSchema];
}
